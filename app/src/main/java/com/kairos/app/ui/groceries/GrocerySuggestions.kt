package com.kairos.app.ui.groceries

/**
 * Every item Kairos ships a custom `kairos:` icon for, with its canonical name —
 * the app-side mirror of the web repo's `src/lib/groceries/suggestions.ts`.
 *
 * The add-an-item list is normally just the household's own catalog, so an item
 * nobody has bought yet isn't offerable and gets typed (and mistyped) by hand.
 * These are shown alongside the catalog, deduped by name, so the whole custom
 * icon set is pickable with the spelling the server's matcher expects.
 *
 * A suggestion is not a catalog row: picking one adds the item by name, and the
 * server creates the catalog entry and guesses the icon — which lands on the icon
 * named here. Bundled rather than fetched so the list works offline; keep it in
 * step with the web file whenever icons are added.
 */
